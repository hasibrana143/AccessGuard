// Generate a branch name for accessibility fixes
export function createFixBranchName(ruleId: string, timestamp?: Date): string {
  const ts = timestamp || new Date();
  const dateStr = ts.toISOString().split('T')[0].replace(/-/g, '');
  const timeStr = ts.getTime().toString(36);
  const sanitizedRuleId = ruleId.toLowerCase().replace(/[^a-z0-9]/g, '-').slice(0, 30);
  
  return `accessguard/fix-${sanitizedRuleId}-${dateStr}-${timeStr}`;
}

// Generate a PR title from violations
export function generatePrTitle(violations: ViolationForPR[]): string {
  if (violations.length === 0) {
    return 'AccessGuard: Accessibility fixes';
  }
  
  const ruleIds = [...new Set(violations.map(v => v.ruleId))];
  
  if (ruleIds.length === 1) {
    const ruleName = ruleIds[0].replace(/-/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
    return `fix(a11y): ${ruleName} (${violations.length} occurrence${violations.length > 1 ? 's' : ''})`;
  }
  
  const criticalCount = violations.filter(v => v.severity === 'critical').length;
  const seriousCount = violations.filter(v => v.severity === 'serious').length;
  
  if (criticalCount > 0) {
    return `fix(a11y): ${violations.length} accessibility issues (${criticalCount} critical)`;
  }
  
  if (seriousCount > 0) {
    return `fix(a11y): ${violations.length} accessibility issues (${seriousCount} serious)`;
  }
  
  return `fix(a11y): ${violations.length} accessibility improvements`;
}

/** Neutralize raw HTML and Markdown syntax in untrusted text. */
export function escapeMarkdownText(value: string): string {
  const amp = String.fromCharCode(38);
  const withoutHtml = value.split('<').join(`${amp}lt;`).split('>').join(`${amp}gt;`);
  // Markdown syntax outside a code block: links, images, mentions, emphasis,
  // headings and lists. A backslash escapes it without changing the rendering.
  const escaped = withoutHtml.replace(/([\\`*_{}[\]()#+\-=!|~@])/g, '\\$1');
  // GFM turns a bare URL into a link even without any Markdown syntax, so the
  // scheme of a URL is neutralized as well. The entity is decoded by the
  // renderer, so the text still reads as the URL — it is just not a link.
  return escaped
    .replace(/\b(https?|ftp):\/\//gi, (_match, scheme: string) => `${scheme}${amp}#58;//`)
    .replace(/\bwww\./gi, `www${amp}#46;`);
}

/** An inline code span that the value cannot break out of. */
export function inlineCode(value: string): string {
  // The fence must be longer than the longest backtick run inside the value,
  // otherwise the value closes the span and the rest of it is rendered as
  // Markdown (an attacker controlled selector could inject a live link).
  let longest = 0;
  for (const match of value.matchAll(/`+/g)) longest = Math.max(longest, match[0].length);
  const ticks = '`'.repeat(longest + 1);
  // A value that starts or ends with a backtick needs padding, or the fence
  // would be read as part of the content.
  const pad = value.startsWith('`') || value.endsWith('`') ? ' ' : '';
  return `${ticks}${pad}${value}${pad}${ticks}`;
}

/** A code fence long enough to contain the content it wraps. */
export function codeFence(content: string): string {
  let longest = 2;
  for (const match of content.matchAll(/`+/g)) longest = Math.max(longest, match[0].length);
  return '`'.repeat(Math.max(3, longest + 1));
}

// Generate PR body with violation details
export function generatePrBody(violations: ViolationForPR[], project?: { name: string; url: string }): string {
  const lines: string[] = [
    '## AccessGuard - Accessibility Fixes',
    '',
    'This PR was automatically generated by [AccessGuard](https://accessguard.io) to address accessibility issues.',
    '',
  ];

  if (project) {
    lines.push(`**Project:** ${escapeMarkdownText(project.name)}`);
    lines.push(`**URL:** ${escapeMarkdownText(project.url)}`);
    lines.push('');
  }
  
  // Summary
  const critical = violations.filter(v => v.severity === 'critical').length;
  const serious = violations.filter(v => v.severity === 'serious').length;
  const moderate = violations.filter(v => v.severity === 'moderate').length;
  const minor = violations.filter(v => v.severity === 'minor').length;
  
  lines.push('### Summary');
  lines.push('');
  lines.push(`- **Total Issues:** ${violations.length}`);
  if (critical > 0) lines.push(`- **Critical:** ${critical}`);
  if (serious > 0) lines.push(`- **Serious:** ${serious}`);
  if (moderate > 0) lines.push(`- **Moderate:** ${moderate}`);
  if (minor > 0) lines.push(`- **Minor:** ${minor}`);
  lines.push('');
  
  // Group violations by rule
  const violationsByRule = violations.reduce((acc, v) => {
    if (!acc[v.ruleId]) acc[v.ruleId] = [];
    acc[v.ruleId].push(v);
    return acc;
  }, {} as Record<string, ViolationForPR[]>);
  
  lines.push('### Issues Fixed');
  lines.push('');
  
  for (const [ruleId, ruleViolations] of Object.entries(violationsByRule)) {
    const ruleName = ruleId.replace(/-/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
    lines.push(`#### ${ruleName}`);
    lines.push('');
    
    for (const v of ruleViolations.slice(0, 5)) { // Limit to 5 per rule for readability
      lines.push(`- **[${v.severity.toUpperCase()}]** ${escapeMarkdownText(v.description)}`);
      lines.push(`  - Location: ${escapeMarkdownText(v.url)}`);
      if (v.elementSelector) {
        lines.push(`  - Selector: ${inlineCode(v.elementSelector)}`);
      }
      lines.push('');
    }
    
    if (ruleViolations.length > 5) {
      lines.push(`_... and ${ruleViolations.length - 5} more occurrences_`);
      lines.push('');
    }
  }
  
  // WCAG Criteria
  const wcagCriteria = [...new Set(violations.map(v => v.wcagCriteria).filter(Boolean))];
  if (wcagCriteria.length > 0) {
    lines.push('### WCAG Criteria Addressed');
    lines.push('');
    lines.push(wcagCriteria.map(c => `- WCAG ${c}`).join('\n'));
    lines.push('');
  }
  
  // Footer
  lines.push('---');
  lines.push('');
  lines.push('_This PR was created by AccessGuard. Please review the changes carefully before merging._');
  lines.push('');
  lines.push('**Recommendations:**');
  lines.push('- Review each fix for correctness');
  lines.push('- Test with screen readers');
  lines.push('- Verify no regressions in functionality');
  
  return lines.join('\n');
}

// Attributes whose value is a URI and can therefore carry an active scheme.
const URI_ATTRIBUTES = new Set([
  'href', 'src', 'srcset', 'action', 'formaction', 'xlink:href', 'poster', 'data',
  'cite', 'background', 'longdesc', 'manifest', 'ping', 'profile', 'usemap',
  'codebase', 'archive', 'icon',
]);

// Schemes that may appear in a URI attribute. Everything else (javascript:,
// vbscript:, data:text/html, blob:, file:, about:) can execute or exfiltrate.
const ALLOWED_URI_SCHEMES = new Set(['http', 'https', 'mailto', 'tel', 'ftp']);

// Inert image data URIs are allowed; SVG is not (it can carry script).
const ALLOWED_DATA_URI = /^data:image\/(png|jpe?g|gif|webp|bmp|x-icon)[;,]/;

// Style properties that can take over the screen or cover other content.
const OVERLAY_STYLE_PROPERTIES = new Set([
  'position', 'inset', 'top', 'right', 'bottom', 'left', 'z-index', 'transform',
  'clip-path', 'mask',
]);

/** Check a URI attribute against the scheme allowlist. Returns a reason or null. */
function checkUriAttribute(name: string, value: string): string | null {
  if (!URI_ATTRIBUTES.has(name)) return null;

  // srcset holds a comma separated list of candidate URLs.
  const candidates =
    name === 'srcset'
      ? value.split(',').map(part => part.trim().split(/\s+/)[0] ?? '')
      : [value];

  for (const candidate of candidates) {
    const normalized = normalizeUriValue(candidate);
    if (!normalized) continue;

    const schemeMatch = normalized.match(/^([a-z][a-z0-9+.-]*):/);
    if (!schemeMatch) continue; // relative URL: no scheme to abuse

    const scheme = schemeMatch[1] as string;
    if (ALLOWED_URI_SCHEMES.has(scheme)) continue;
    if (scheme === 'data' && ALLOWED_DATA_URI.test(normalized)) continue;

    return `remediation code contains an active URI scheme in ${name}: ${scheme}:`;
  }

  return null;
}

/**
 * True when a colour value makes the text invisible.
 *
 * `transparent` and every colour with an alpha of zero are invisible: the text
 * stays in the document, so the rendered-text check does not catch it.
 */
function isTransparentColor(value: string): boolean {
  const normalized = value.replace(/\s+/g, '').toLowerCase();
  if (normalized === 'transparent') return true;

  const functional = /^(?:rgba|hsla)\(([^)]*)\)$/.exec(normalized);
  if (functional) {
    const parts = (functional[1] ?? '').split(',');
    if (parts.length < 4) return false;
    const alpha = parts[3] ?? '';
    return /^0(?:\.0+)?$/.test(alpha);
  }

  // The modern syntax: `rgb(0 0 0 / 0)`.
  const slash = /\/\s*([\d.]+)\s*\)$/.exec(normalized);
  if (slash) return Number.parseFloat(slash[1] ?? '') === 0;

  return false;
}

/**
 * Check a style attribute for declarations that can take over the screen.
 *
 * `isTarget` marks the style of the element the fix patches: that element may
 * not be hidden, while a nested element may (a fix that moves the text into a
 * hidden element is caught by the rendered-text check).
 */
function checkStyleAttribute(value: string, isTarget: boolean): string | null {
  // A browser decodes the entities of the attribute value, treats a CSS comment
  // as whitespace (`position/**/:fixed` is `position: fixed`) and resolves the
  // CSS escapes (`p\6fsition:fixed` is `position: fixed`) before it reads a
  // declaration. A partial entity table cannot mirror that, so a style value
  // that carries any of these is rejected instead of guessed.
  if (/[&\\]|\/\*|\*\//.test(value)) {
    return 'remediation code hides an overlay-capable style behind an entity, an escape or a comment';
  }

  const decoded = value;

  for (const declaration of decoded.split(';')) {
    const separator = declaration.indexOf(':');
    if (separator === -1) continue;

    const property = declaration.slice(0, separator).trim().toLowerCase();
    // The priority suffix is not part of the value: `opacity:0!important`
    // hides the element just like `opacity:0`.
    const cssValue = declaration
      .slice(separator + 1)
      .trim()
      .toLowerCase()
      .replace(/\s*!\s*important\s*$/, '')
      .trim();
    if (!property) continue;

    if (OVERLAY_STYLE_PROPERTIES.has(property)) {
      return `remediation code sets an overlay-capable style property: ${property}`;
    }
    if (/(^|[^a-z])(vw|vh|vmin|vmax)([^a-z]|$)/.test(cssValue)) {
      return 'remediation code sizes an element with viewport units';
    }
    if (cssValue.includes('url(') || cssValue.includes('expression(')) {
      return 'remediation code loads or executes CSS content';
    }
    // A transparent element is an invisible element: the text stays in the
    // document, so the rendered-text check does not catch it.
    if (property === 'opacity' && /^0(\.0+)?$/.test(cssValue)) {
      return 'remediation code hides the element with opacity: 0';
    }
    // The same holds for the element itself: a fix that hides the element it
    // patches replaces a visible element with an invisible one.
    if (isTarget && property === 'display' && cssValue === 'none') {
      return 'remediation code hides the element with display: none';
    }
    if (isTarget && property === 'visibility' && /^(hidden|collapse)$/.test(cssValue)) {
      return 'remediation code hides the element with visibility: hidden';
    }
    // Transparent text is invisible text: the user reads nothing although the
    // text is still in the document.
    if (
      (property === 'color' || property === '-webkit-text-fill-color') &&
      isTransparentColor(cssValue)
    ) {
      return 'remediation code makes the text transparent';
    }
  }

  return null;
}

/**
 * Server-template grammar.
 *
 * The template engine of the customer's build evaluates these markers, so a
 * file that carries them is a template and not HTML, and a fix that carries
 * them becomes executable code on the customer's server.
 */
const TEMPLATE_MARKERS = /<%|%>|<\?|\?>|{%|%}|{{|}}|{#|#}/;

/** True when the content carries server-template grammar. */
export function containsTemplateGrammar(content: string): boolean {
  return TEMPLATE_MARKERS.test(content);
}

/** The class tokens of every tag in a snippet. */
function classTokensOf(html: string): string[] {
  const tokens: string[] = [];
  for (const attribute of parseHtmlAttributes(html)) {
    if (attribute.name !== 'class') continue;
    for (const token of attribute.value.split(/\s+/)) {
      if (token) tokens.push(token.toLowerCase());
    }
  }
  return tokens;
}

/**
 * The remote URLs of a snippet.
 *
 * A URL is remote when it carries an `http` or `https` scheme. A relative URL
 * stays inside the customer's own site and cannot call home.
 */
function remoteUrlsOf(html: string): string[] {
  const urls: string[] = [];

  for (const attribute of parseHtmlAttributes(html)) {
    if (!URI_ATTRIBUTES.has(attribute.name)) continue;

    // `srcset` holds a comma separated list of candidate URLs.
    const candidates =
      attribute.name === 'srcset'
        ? attribute.value.split(',').map(part => part.trim().split(/\s+/)[0] ?? '')
        : [attribute.value];

    for (const candidate of candidates) {
      // The scheme is read the way the browser reads it (entities decoded,
      // control characters removed); the URL itself is compared as it is.
      const normalized = normalizeUriValue(candidate);
      if (!/^https?:\/\//.test(normalized)) continue;
      urls.push(decodeHtmlEntities(candidate).trim());
    }
  }

  return urls;
}

// Validate AI-generated remediation code before applying it to source files
export function validateRemediation(
  remediationCode: string | null | undefined,
  originalElementHtml?: string | null
): { valid: boolean; reason?: string } {  if (!remediationCode || !remediationCode.trim()) {
    return { valid: false, reason: 'empty remediation code' };
  }

  const code = remediationCode.trim();

  if (code.length > 20_000) {
    return { valid: false, reason: 'remediation code exceeds 20k characters' };
  }

  // No script tag — in any spelling (`<script>`, `<script/x>`, `< script >`).
  if (/<\s*\/?\s*script\b/i.test(code)) {
    return { valid: false, reason: 'remediation code introduces a <script> tag' };
  }

  // No active or embedding elements: they execute code, load remote content or
  // rewrite the document. `frame`/`frameset` load a remote document into the
  // customer's page, so they are rejected like every other embedding element;
  // `portal` and `fencedframe` load a document the same way, and `math` (like
  // `svg`) can carry foreign content that the HTML parser executes.
  // `plaintext` (like `xmp` and `noscript`) makes the browser read the rest of
  // the document as raw text, which removes the remaining UI; `video`, `audio`,
  // `source` and `track` load remote resources from the customer's browser.
  const ACTIVE_TAGS = [
    'iframe', 'object', 'embed', 'applet', 'base', 'svg', 'style', 'link', 'meta',
    'frame', 'frameset', 'noframes', 'portal', 'fencedframe', 'math',
    'plaintext', 'xmp', 'listing', 'noscript', 'noembed',
    'video', 'audio', 'source', 'track',
  ];
  for (const tag of ACTIVE_TAGS) {
    if (new RegExp(`<\\s*/?\\s*${tag}\\b`, 'i').test(code)) {
      return { valid: false, reason: `remediation code introduces a <${tag}> element` };
    }
  }

  // An `<input type="image">` loads a remote resource from the customer's
  // browser, like the other resource loaders above. The type is read the way
  // the browser reads it: an entity is decoded first (`im&#97;ge` is `image`),
  // and a value that carries an entity the decoder does not know is rejected
  // instead of guessed.
  if (/<input\b/i.test(code)) {
    const typeAttr = parseHtmlAttributes(code).find(a => a.name === 'type');
    if (typeAttr) {
      const raw = typeAttr.value.trim();
      if (raw.includes('&')) {
        return { valid: false, reason: 'remediation code introduces an <input> whose type carries an entity' };
      }
      if (raw.toLowerCase() === 'image' || decodeHtmlEntities(raw).trim().toLowerCase() === 'image') {
        return { valid: false, reason: 'remediation code introduces an <input type="image"> element' };
      }
    }
  }

  // No HTML comment syntax: a comment ends at the first `-->`, so a comment
  // opener in the remediation swallows the markup that follows it in the
  // customer's page.
  if (/<!--|-->|--!>/.test(code)) {
    return { valid: false, reason: 'remediation code contains HTML comment syntax' };
  }

  // No server-template grammar: `<% … %>`, `<? … ?>` and `{{ … }}` are
  // evaluated by the template engine of the customer's build, so a fix that
  // carries them becomes executable code on the customer's server.
  if (containsTemplateGrammar(code)) {
    return { valid: false, reason: 'remediation code contains server-template syntax' };
  }

  // No braces: in JSX they open an expression, and in a template file they
  // open an interpolation. The remediation is validated as HTML and then
  // written into the source, so a brace would become executable code there.
  if (/[{}]/.test(code)) {
    return { valid: false, reason: 'remediation code contains a brace, which becomes an expression in the target source' };
  }

  // The remediation may not add a class the original element does not have: a
  // class is a hook into the repository's stylesheet, and the effect of that
  // stylesheet is not part of the isolated verification.
  if (originalElementHtml) {
    const originalClasses = classTokensOf(originalElementHtml);
    const added = classTokensOf(code).filter(token => !originalClasses.includes(token));
    if (added.length > 0) {
      return { valid: false, reason: 'remediation code adds a class the original element does not have' };
    }
  }

  // The remediation may not introduce a remote URL the original element does
  // not have: the verification browser blocks every network request, so a new
  // URL is invisible to it. Once the fix is written, that URL loads from the
  // customer's browser (a tracking pixel) or points the user somewhere else.
  if (originalElementHtml) {
    const originalUrls = new Set(remoteUrlsOf(originalElementHtml));
    for (const url of remoteUrlsOf(code)) {
      if (!originalUrls.has(url)) {
        return {
          valid: false,
          reason: 'remediation code introduces a remote URL the original element does not have',
        };
      }
    }
  }

  // No javascript:, vbscript: or data:text/html URIs — quoted or unquoted.
  if (/\b(?:javascript|vbscript)\s*:/i.test(code) || /\bdata\s*:\s*text\/html/i.test(code)) {
    return { valid: false, reason: 'remediation code contains an active URI scheme' };
  }

  // Attributes are parsed the way a browser parses them. An event handler is
  // rejected unconditionally: the scanned page may already carry one, and the
  // handler's code is attacker controlled either way. Every URI attribute is
  // checked against a scheme allowlist after entity decoding.
  //
  // The first tag of the remediation is the element the fix patches: it may
  // not hide itself.
  const tags = parseHtmlTags(code);
  for (const [index, tag] of tags.entries()) {
    const isTarget = index === 0;

    for (const attribute of tag.attributes) {
      if (isEventHandlerAttribute(attribute.name)) {
        return { valid: false, reason: `remediation code contains an event handler: ${attribute.name}` };
      }

      // A fix may not hide the element it patches: the rule check passes while
      // the user loses the element.
      if (isTarget && attribute.name === 'hidden') {
        return { valid: false, reason: 'remediation code hides the patched element with the hidden attribute' };
      }

      const uriProblem = checkUriAttribute(attribute.name, attribute.value);
      if (uriProblem) return { valid: false, reason: uriProblem };

      if (attribute.name === 'style') {
        const styleProblem = checkStyleAttribute(attribute.value, isTarget);
        if (styleProblem) return { valid: false, reason: styleProblem };
      }
    }
  }

  // No unclosed HTML tags (rough balance check for common void-safe tags)
  const tagNames = [...new Set([...code.matchAll(/<\/?([a-z][a-z0-9-]*)\b/gi)].map((m) => m[1].toLowerCase()))];
  const voidTags = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr']);
  for (const tag of tagNames) {
    if (voidTags.has(tag)) continue;
    const open = (code.match(new RegExp(`<${tag}(\\s[^>]*)?(?<!/)>`, 'gi')) || []).length;
    const close = (code.match(new RegExp(`</${tag}\\s*>`, 'gi')) || []).length;
    if (open > close) {
      return { valid: false, reason: `unclosed <${tag}> tag in remediation code` };
    }
  }

  return { valid: true };
}

/**
 * Full pre-flight for a fix: injection safety, placeholder rejection and the
 * per-rule check that the remediation addresses the rule it claims to fix.
 */
export function validateFixCandidate(v: FileFixViolation): { valid: boolean; reason?: string } {
  if (!v.remediationCode) return { valid: false, reason: 'empty remediation code' };

  const validation = validateRemediation(v.remediationCode, v.elementHtml);
  if (!validation.valid) return { valid: false, reason: validation.reason };

  if (containsPlaceholder(v.remediationCode)) {
    return { valid: false, reason: 'remediation still contains a placeholder' };
  }

  const ruleCheck = validateFixForRule(v.ruleId, v.remediationCode, v.elementHtml);
  if (!ruleCheck.valid) return { valid: false, reason: `does not fix rule: ${ruleCheck.reason}` };

  return { valid: true };
}

/**
 * Occurrences are counted per rule AND per element, so three copies of the same
 * image are patched one by one while two different images are patched independently.
 */
export function fixOccurrenceKey(v: { ruleId: string; elementHtml?: string | null }): string {
  return `${v.ruleId}::${v.elementHtml ?? ''}`;
}

/**
 * The element keys whose selected fixes carry different remediations.
 *
 * The fixes are matched to the occurrences of the element in the file in order,
 * and the request order is not the occurrence order: two selected copies of the
 * same element with different remediations would have their remediations
 * swapped. Such a fix cannot be mapped, so it stays a review suggestion.
 */
export function conflictingRemediationKeys(
  violations: Array<{ ruleId: string; elementHtml?: string | null; remediationCode?: string | null }>
): Set<string> {
  const remediations = new Map<string, Set<string>>();
  for (const v of violations) {
    if (!v.elementHtml) continue;
    const key = fixOccurrenceKey(v);
    const set = remediations.get(key) ?? new Set<string>();
    set.add((v.remediationCode ?? '').trim());
    remediations.set(key, set);
  }
  return new Set(
    [...remediations.entries()].filter(([, set]) => set.size > 1).map(([key]) => key)
  );
}

// Apply fixes to file content
export function applyFixesToFile(
  originalContent: string,
  violations: FileFixViolation[],
  filePath: string
): { content: string; fixesApplied: number; errors: string[] } {
  const errors: string[] = [];
  const unmatched: FileFixViolation[] = [];
  const occurrenceByKey = new Map<string, number>();
  const targets: Array<{ start: number; end: number; replacement: string }> = [];
  const claimed: Array<{ start: number; end: number }> = [];

  // The destination context has to be provable. An HTML file that carries
  // server-template grammar is a template, not HTML: the template engine of the
  // customer's build evaluates its markers, so a fix written into it becomes
  // executable server code. Nothing is written into such a file — not even the
  // review comment, because the engine would evaluate the comment as well.
  if (/\.html?$/i.test(filePath) && containsTemplateGrammar(originalContent)) {
    return {
      content: originalContent,
      fixesApplied: 0,
      errors: ['the file carries server-template syntax, so no fix is written into it'],
    };
  }

  // How many fixes were selected per element. The fixes are matched to the
  // occurrences of the element in the file in order, so the mapping is only
  // provable when every occurrence is covered: selecting the second of two
  // identical elements would otherwise patch the first one.
  const selectedByKey = new Map<string, number>();
  for (const v of violations) {
    if (!v.elementHtml) continue;
    const key = fixOccurrenceKey(v);
    selectedByKey.set(key, (selectedByKey.get(key) ?? 0) + 1);
  }

  // Selected fixes for the same element with different remediations cannot be
  // mapped to the occurrences (the request order is not the occurrence order).
  const conflictingKeys = conflictingRemediationKeys(violations);

  for (const v of violations) {
    if (!v.remediationCode) continue;

    const validation = validateFixCandidate(v);
    if (!validation.valid) {
      errors.push(`[${v.ruleId}] skipped: ${validation.reason}`);
      continue;
    }

    if (!v.elementHtml) {
      unmatched.push(v);
      continue;
    }

    const key = fixOccurrenceKey(v);
    if (conflictingKeys.has(key)) {
      unmatched.push(v);
      continue;
    }

    // The destination context has to be provable: an HTML file or a JSX
    // element. In any other file the element text can sit inside a string or
    // an expression, and the fix would become code.
    if (!isPatchableFile(filePath)) {
      unmatched.push(v);
      continue;
    }
    const occurrences = countElementOccurrences(originalContent, filePath, v.elementHtml);
    if (occurrences > (selectedByKey.get(key) ?? 0)) {
      unmatched.push(v);
      continue;
    }

    const occurrence = occurrenceByKey.get(key) ?? 0;
    const location = locateElement(originalContent, filePath, v.elementHtml, occurrence);
    if (!location) {
      unmatched.push(v);
      continue;
    }
    occurrenceByKey.set(key, occurrence + 1);

    const originalElement = originalContent.slice(location.start, location.end);
    const replacement = buildReplacement(filePath, v.remediationCode);
    if (replacement.trim() === originalElement.trim()) {
      errors.push(`[${v.ruleId}] skipped: patch is identical to the original element (no-op)`);
      continue;
    }
    if (!preservesVisibleContent(originalElement, replacement)) {
      errors.push(`[${v.ruleId}] skipped: patch removes the visible text of the element`);
      continue;
    }
    // A fix may not hide the element it patches: the rule check passes while
    // the user loses the element.
    if (hidesOwnTarget(replacement)) {
      errors.push(`[${v.ruleId}] skipped: patch hides the element it patches`);
      continue;
    }
    if (claimed.some(c => location.start < c.end && location.end > c.start)) {
      errors.push(`[${v.ruleId}] skipped: target element was already patched`);
      continue;
    }

    claimed.push(location);
    targets.push({ ...location, replacement });
  }

  // Splice from the end so earlier offsets stay valid.
  let content = originalContent;
  for (const target of [...targets].sort((a, b) => b.start - a.start)) {
    content = content.slice(0, target.start) + target.replacement + content.slice(target.end);
  }

  if (targets.length > 0 && hasSyntaxErrors(content, filePath)) {
    errors.push('patched file no longer parses; all patches discarded');
    content = originalContent;
    targets.length = 0;
  }

  const fixesApplied = targets.length;

  // Fallback for violations we could not apply: attach review comments at the top
  if (unmatched.length > 0) {
    const fixComment = generateFixComment(filePath, unmatched);
    if (!content.includes('AccessGuard Accessibility Fixes')) {
      content = fixComment + '\n\n' + content;
    }
  }

  return { content, fixesApplied, errors };
}

/**
 * Neutralize the terminator of a source comment. The description, the
 * explanation and the remediation come from the scanned page (through the
 * model), so a comment terminator inside them would close the comment and
 * turn the rest of the text into code in the customer's file.
 */
function neutralizeCommentTerminator(value: string, terminator: string): string {
  if (terminator === '*/') return value.replace(/\*\//g, '*\\/');
  // An HTML comment ends at `-->` **and** at `--!>`; both have to be neutralized.
  return value.replace(/-->/g, '--\\>').replace(/--!>/g, '--!\\>');
}

// Generate a fix comment block
function generateFixComment(
  filePath: string,
  violations: FileFixViolation[]
): string {
  const lines: string[] = [];

  // Determine file type for comment syntax
  const ext = filePath.split('.').pop()?.toLowerCase();
  const commentStart = ['js', 'jsx', 'ts', 'tsx', 'css', 'scss', 'sass'].includes(ext || '')
    ? '/*'
    : '<!--';
  const commentEnd = ['js', 'jsx', 'ts', 'tsx', 'css', 'scss', 'sass'].includes(ext || '')
    ? '*/'
    : '-->';
  const safe = (value: string) => neutralizeCommentTerminator(value, commentEnd);

  lines.push(`${commentStart}`);
  lines.push(' * AccessGuard Accessibility Fixes');
  lines.push(' * ');
  lines.push(` * File: ${safe(filePath)}`);
  lines.push(' * ');
  lines.push(' * Issues Found:');

  for (const v of violations) {
    lines.push(` * - [${(v.severity || 'N/A').toUpperCase()}] ${v.ruleId}: ${safe(v.description || 'Accessibility violation')}`);
  }

  lines.push(' * ');
  lines.push(' * Suggested Fixes:');

  for (const v of violations) {
    if (v.remediationCode) {
      lines.push(' * ---');
      lines.push(` * Rule: ${v.ruleId}`);
      if (v.aiExplanation) {
        lines.push(` * Explanation: ${safe(v.aiExplanation)}`);
      }
      lines.push(' * Code:');
      for (const codeLine of v.remediationCode.split('\n')) {
        lines.push(` *   ${safe(codeLine)}`);
      }
    }
  }

  lines.push(`${commentEnd}`);

  return lines.join('\n');
}

// Parse GitHub PR URL
export function parsePrUrl(url: string): { owner: string; repo: string; pullNumber: number } | null {
  const match = url.match(/github\.com\/([^/]+)\/([^/]+)\/pull\/(\d+)/);
  if (!match) return null;
  
  return {
    owner: match[1],
    repo: match[2],
    pullNumber: parseInt(match[3], 10),
  };
}


